test.afterAll(async () => {
  // Only the synthetic records generated by this run, on the guarded local host.
  const ids = fixtures.map((f) => f.id);
  for (const id of ids) {
    const resources = await service
      .from("som_resources")
      .select("bucket,path")
      .eq("owner_id", id);
    for (const bucket of ["ministry-curriculum", "ministry-submissions"]) {
      const paths = [
        ...new Set(
          (resources.data ?? [])
            .filter((r) => r.bucket === bucket)
            .map((r) => r.path.split("#ref-")[0]),
        ),
      ];
      if (paths.length) await service.storage.from(bucket).remove(paths);
    }
  }
  for (const id of ids) {
    await service
      .from("som_grades")
      .delete()
      .in(
        "work_id",
        (
          await service.from("som_work").select("id").eq("user_id", id)
        ).data?.map((x) => x.id) ?? [],
      );
    await service.from("som_resources").delete().eq("owner_id", id);
    await service.from("som_work").delete().eq("user_id", id);
    await service.from("som_progress").delete().eq("user_id", id);
    await service.from("som_attendance").delete().eq("user_id", id);
    await service
      .from("som_recommendations")
      .delete()
      .or(`user_id.eq.${id},instructor_id.eq.${id}`);
    const es = await service
      .from("som_enrollments")
      .select("id")
      .eq("user_id", id);
    if (es.data?.length)
      await service
        .from("som_ledger")
        .delete()
        .in(
          "enrollment_id",
          es.data.map((x) => x.id),
        );
    await service.from("som_enrollments").delete().eq("user_id", id);
    await service.from("som_instructors").delete().eq("user_id", id);
  }
  for (const id of contentIds) {
    await service.from("som_resources").delete().eq("content_id", id);
    await service.from("som_content").delete().eq("id", id);
  }
  for (const f of fixtures) {
    const deleted = await service.auth.admin.deleteUser(f.id);
    expect(deleted.error, "Synthetic local account cleanup").toBeNull();
  }
});
