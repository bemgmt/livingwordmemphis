function checked<
  T extends { data: unknown; error: { message: string } | null },
>(r: T): T["data"] {
  if (r.error) throw Error(r.error.message);
  return r.data;
}
async function createFixture(role?: string) {
  const password = randomUUID() + "Aa1!",
    email = `ministry-${randomUUID()}@example.test`;
  const user = checked(
    await service.auth.admin.createUser({
      email,
      password,
      email_confirm: true,
      user_metadata: {
        display_name:
          role === "executive"
            ? "Ministry administrator"
            : "Ministry test member",
      },
    }),
  ).user!;
  const f = { id: user.id, email, password };
  fixtures.push(f);
  if (role)
    checked(
      await service.from("user_roles").insert({ user_id: user.id, role }),
    );
  return f;
}
async function login(context: BrowserContext, f: (typeof fixtures)[number]) {
  const cookies: { name: string; value: string }[] = [];
  const auth = createServerClient(
    url,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    {
      cookies: {
        getAll: () => cookies,
        setAll: (values: { name: string; value: string }[]) => {
          for (const c of values) {
            const i = cookies.findIndex((x) => x.name === c.name);
            if (i >= 0) cookies[i] = c;
            else cookies.push(c);
          }
        },
      },
    },
  );
  checked(
    await auth.auth.signInWithPassword({
      email: f.email,
      password: f.password,
    }),
  );
  await context.addCookies(
    cookies.map((c) => ({
      ...c,
      domain: "127.0.0.1",
      path: "/",
      httpOnly: false,
      secure: false,
      sameSite: "Lax" as const,
    })),
  );
}
